window.currentLang = localStorage.getItem('nutritrack-lang') || 'en';

window.t = function(key) {
  const dict = window.I18N_DICTIONARY[window.currentLang] || window.I18N_DICTIONARY['en'];
  return dict[key] || window.I18N_DICTIONARY['en'][key] || key;
};

window.setLanguage = function(lang) {
  if (!window.I18N_DICTIONARY[lang]) return;
  window.currentLang = lang;
  localStorage.setItem('nutritrack-lang', lang);

  const select = document.getElementById('langSelect');
  if (select) select.value = lang;

  if (typeof updateLanguageUI === 'function') {
    updateLanguageUI();
  }
};
